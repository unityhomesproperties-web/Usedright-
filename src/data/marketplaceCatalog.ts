function normalizeListing(item: DeviceListing): DeviceListing {
  return {
    ...item,
    cosmeticDescription: item.cosmeticDescription
      ? sanitizeConditionText(item.cosmeticDescription)
      : undefined,
    disclosedFaults: (item.disclosedFaults || []).map((f) => sanitizeConditionText(f)),
    disclosedFaultsList: (item.disclosedFaultsList || []).map((f) => ({
      ...f,
      label: sanitizeConditionText(f.label),
      description: sanitizeConditionText(f.description),
    })),
    thingsToKnow: (item.thingsToKnow || []).map((t) => sanitizeConditionText(t)),
    modelYear: item.modelYear || (item.model.includes('13') ? 2021 : item.model.includes('14') ? 2022 : item.model.includes('12') ? 2020 : 2022),
    yearMadePrecision: item.yearMadePrecision || 'approximate',
    yearMade: item.yearMade || (item.model.includes('13') ? 2022 : undefined),
    stockQuantity: item.stockQuantity ?? item.totalStock ?? 3,
    totalStock: item.totalStock ?? (item.variations ? item.variations.reduce((s, v) => s + v.stockQuantity, 0) : item.stockQuantity ?? 3),
  };
}

